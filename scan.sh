#!/usr/bin/env bash
# Scan a repository and draft the mechanical half of AGENTS.md.
#
# Usage:
#   bash scan.sh                 # scan the current directory, print to stdout
#   bash scan.sh /path/to/repo   # scan a specific repo
#   bash scan.sh > /tmp/facts.md # save first, then paste into AGENTS.md
#
# Design rule: emit only what is **mechanically determinable**. Anything that requires judgement
# (architecture invariants, prohibition boundaries) is printed as a question, never as a guess.
# Commands and paths invented by an LLM are the most common defect in this setup.
set -uo pipefail

ROOT="${1:-.}"
if [ ! -d "$ROOT" ]; then
  echo "No such directory: $ROOT" >&2
  exit 1
fi
cd "$ROOT" || exit 1

PRUNE="-name .git -o -name node_modules -o -name .venv -o -name venv -o -name dist -o -name build -o -name out -o -name target -o -name vendor -o -name .next -o -name coverage -o -name .idea -o -name .gradle -o -name __pycache__"

list_files() {
  find . \( $PRUNE \) -prune -o -type f -print 2>/dev/null
}

has() { [ -f "$1" ]; }
sec() { printf '\n## %s\n\n' "$1"; }

FILE_COUNT=$(list_files | wc -l | tr -d ' ')
printf '<!-- Generated by scan.sh at %s. Reference material for filling in AGENTS.md. -->\n' "$(date '+%Y-%m-%d %H:%M')"
printf '\n# Fact-layer draft: %s\n' "$(basename "$(pwd)")"
printf '\nRepo size: %s files (node_modules / build output / virtualenvs excluded)\n' "$FILE_COUNT"

# ---------------------------------------------------------------- 1. stack
sec "1. Stack and package manager (mechanically determined, adopt directly)"

printf '| Detected | File |\n| --- | --- |\n'
FOUND_MANIFEST=0
for f in package.json pnpm-lock.yaml package-lock.json yarn.lock bun.lockb \
         pyproject.toml poetry.lock uv.lock Pipfile requirements.txt setup.py \
         go.mod Cargo.toml pom.xml build.gradle build.gradle.kts \
         Gemfile composer.json Makefile CMakeLists.txt Dockerfile; do
  if has "$f"; then
    printf '| %s | `%s` |\n' "$f" "$f"
    FOUND_MANIFEST=1
  fi
done
[ "$FOUND_MANIFEST" -eq 0 ] && printf '| No manifest found | — |\n'

printf '\n### Package manager\n\n'
PM_NOTE=0
if has pnpm-lock.yaml; then echo '- **pnpm** (`pnpm-lock.yaml` present)'; PM_NOTE=1; fi
if has yarn.lock; then echo '- **yarn** (`yarn.lock` present)'; PM_NOTE=1; fi
if has package-lock.json; then echo '- **npm** (`package-lock.json` present)'; PM_NOTE=1; fi
if has bun.lockb; then echo '- **bun** (`bun.lockb` present)'; PM_NOTE=1; fi
if has poetry.lock; then echo '- **poetry**'; PM_NOTE=1; fi
if has uv.lock; then echo '- **uv**'; PM_NOTE=1; fi
if has Pipfile; then echo '- **pipenv**'; PM_NOTE=1; fi
if has go.mod; then echo '- **go modules**'; PM_NOTE=1; fi
if has Cargo.toml; then echo '- **cargo**'; PM_NOTE=1; fi
if has pom.xml; then echo '- **maven**'; PM_NOTE=1; fi
if [ -x ./gradlew ]; then echo '- **gradle wrapper** (executable `gradlew` present)'; PM_NOTE=1; fi
[ "$PM_NOTE" -eq 0 ] && echo '- No lockfile detected; confirm manually'

# Multiple JS lockfiles is the number one cause of wrong commands.
JS_LOCKS=0
for f in pnpm-lock.yaml package-lock.json yarn.lock bun.lockb; do has "$f" && JS_LOCKS=$((JS_LOCKS + 1)); done
if [ "$JS_LOCKS" -gt 1 ]; then
  printf '\n> **Warning: %s JS lockfiles present at once.** Decide which package manager is authoritative first, otherwise your commands will be wrong indefinitely.\n' "$JS_LOCKS"
fi

# Frameworks and main dependencies
if has package.json && command -v node >/dev/null 2>&1; then
  DEPS=$(node -e 'try{const p=require("./package.json");const d=Object.assign({},p.dependencies,p.devDependencies);process.stdout.write(Object.keys(d).join(" "))}catch(e){}' 2>/dev/null)
  printf '\n### Main frameworks / dependencies\n\n'
  KNOWN="react react-dom vue svelte @angular/core next nuxt vite webpack express fastify koa @nestjs/core prisma drizzle-orm mongoose sequelize typeorm zod jest vitest mocha playwright @playwright/test eslint prettier typescript tailwindcss"
  HIT=0
  for k in $KNOWN; do
    case " $DEPS " in
      *" $k "*) printf -- '- %s\n' "$k"; HIT=1 ;;
    esac
  done
  [ "$HIT" -eq 0 ] && echo '- No common framework matched; confirm manually'
fi

# ---------------------------------------------------------------- 2. commands
sec "2. Candidate commands (verify by executing before writing into AGENTS.md)"

printf '### From package.json scripts\n\n'
if has package.json && command -v node >/dev/null 2>&1; then
  SCRIPTS=$(node -e 'try{const s=require("./package.json").scripts||{};for(const k of Object.keys(s))console.log(k+" -> "+s[k])}catch(e){}' 2>/dev/null)
  if [ -n "$SCRIPTS" ]; then
    printf '```\n%s\n```\n' "$SCRIPTS"
  else
    echo '_No scripts in package.json_'
  fi
else
  echo '_No package.json, or node is not installed_'
fi

printf '\n### From Makefile\n\n'
if has Makefile; then
  TARGETS=$(grep -E '^[a-zA-Z0-9_.-]+:' Makefile | sed 's/:.*//' | grep -v '^\.' | head -25 | tr '\n' ' ')
  if [ -n "$TARGETS" ]; then
    printf '```\nmake %s\n```\n' "$(echo "$TARGETS" | sed 's/ *$//')"
  else
    echo '_No usable targets in Makefile_'
  fi
else
  echo '_No Makefile_'
fi

printf '\n### From CI config (closest to how it really runs)\n\n'
CI_FILES=$(find . -maxdepth 4 -path ./.git -prune -o -path '*/workflows/*' -name '*.y*ml' -print 2>/dev/null | head -5)
if [ -n "$CI_FILES" ]; then
  printf '```\n'
  for f in $CI_FILES; do
    echo "# $f"
    grep -E '^[[:space:]]*(-[[:space:]]+)?run:' "$f" 2>/dev/null | sed -e 's/^[[:space:]]*//' -e 's/^- //' -e 's/^run:[[:space:]]*//' | head -8
  done
  printf '```\n'
else
  echo '_No .github/workflows or similar CI config found_'
fi

printf '\n### Default commands for other stacks (verify these)\n\n'
OTHER=0
if has go.mod; then echo '- `go build ./...` / `go test ./...`'; OTHER=1; fi
if has Cargo.toml; then echo '- `cargo build` / `cargo test` / `cargo clippy`'; OTHER=1; fi
if has pom.xml; then echo '- `mvn -q test` / `mvn -q verify`'; OTHER=1; fi
if [ -x ./gradlew ]; then echo '- `./gradlew test` / `./gradlew build`'; OTHER=1; fi
if has pyproject.toml || has setup.py || has requirements.txt; then
  if grep -qsE 'pytest' pyproject.toml setup.py requirements.txt tox.ini 2>/dev/null; then echo '- `pytest`'; OTHER=1; fi
  if has pyproject.toml && grep -qsE 'ruff' pyproject.toml 2>/dev/null; then echo '- `ruff check .`'; OTHER=1; fi
  if has pyproject.toml && grep -qsE 'mypy' pyproject.toml 2>/dev/null; then echo '- `mypy .`'; OTHER=1; fi
fi
[ "$OTHER" -eq 0 ] && echo '- None'

# ---------------------------------------------------------------- 3. constraints
sec "3. Existing constraint configs (reference them, do not restate them as prose)"

printf '| Kind | File |\n| --- | --- |\n'
C=0
for f in .eslintrc .eslintrc.js .eslintrc.cjs .eslintrc.json .eslintrc.yml eslint.config.js eslint.config.mjs \
         .prettierrc .prettierrc.json prettier.config.js \
         .dependency-cruiser.js .dependency-cruiser.json .dependency-cruiser.cjs \
         .importlinter importlinter.ini \
         commitlint.config.js .commitlintrc.json \
         tsconfig.json ruff.toml .ruff.toml mypy.ini .golangci.yml .golangci.yaml \
         .editorconfig .python-version .nvmrc .tool-versions; do
  if has "$f"; then printf '| config | `%s` |\n' "$f"; C=1; fi
done
for d in .husky .github/hooks; do
  if [ -d "$d" ]; then printf '| hook | `%s/` |\n' "$d"; C=1; fi
done
if [ -d .github/instructions ]; then printf '| path-scoped instructions | `.github/instructions/` |\n'; C=1; fi
[ "$C" -eq 0 ] && printf '| none found | — |\n'

# ------------------------------------------------- 3.1 what is already there
# Installing on top of an existing setup is the normal case, not the exception. Two things break:
# two files that both claim to hold the project rules (they disagree, the model picks one silently),
# and two agents that both own the same role (you pick one at random and get different behaviour).
printf '\n### Existing agent and instruction assets (read before adding anything)\n\n'
printf 'Everything listed here keeps being loaded alongside whatever you add later.\n\n'

printf '| Asset | Path | Loaded by |\n| --- | --- | --- |\n'
A=0
asset() { if [ -e "$2" ]; then printf '| %s | `%s` | %s |\n' "$1" "$2" "$3"; A=$((A+1)); fi; }
asset "project rules" AGENTS.md "Copilot (VS Code, JetBrains), Codex"
asset "project rules" CLAUDE.md "Claude Code; Copilot also reads it"
asset "project rules" .github/copilot-instructions.md "Copilot"
asset "project rules" GEMINI.md "Gemini CLI"
asset "project rules" .cursor/rules "Cursor"
asset "project rules" .windsurfrules "Windsurf"
asset "project rules" .junie/guidelines.md "JetBrains Junie"
asset "project rules" .aiassistant/rules "JetBrains AI Assistant"
asset "agent profiles" .github/agents "Copilot agent picker"
asset "agent profiles" .claude/agents "Claude Code subagents"
asset "path-scoped rules" .github/instructions "Copilot, by applyTo glob"
asset "prompt files" .github/prompts "Copilot, as /commands"
asset "skills" .github/skills "Copilot skills"
asset "skills" .claude/skills "Claude Code skills"
[ "$A" -eq 0 ] && printf '| none found | — | — |\n'

FACT=0
for f in AGENTS.md CLAUDE.md GEMINI.md .github/copilot-instructions.md .junie/guidelines.md .windsurfrules; do
  [ -f "$f" ] && FACT=$((FACT + 1))
done
[ -d .cursor/rules ] && FACT=$((FACT + 1))
[ -d .aiassistant/rules ] && FACT=$((FACT + 1))
if [ "$FACT" -gt 1 ]; then
  printf '\n> **Warning: %s files claim to hold the project rules.** They are all loaded and they will\n' "$FACT"
  printf '> disagree eventually. Keep one canonical (`AGENTS.md`); make the rest one-line pointers,\n'
  printf '> never copies — a copy is a fork, and forks drift.\n'
fi

if [ -d .github/agents ]; then
  printf '\nAgent profiles in `.github/agents/` — for each role, exactly one of them should be authoritative:\n\n'
  printf '| File | Picker name | Likely role | Note |\n| --- | --- | --- | --- |\n'
  N=0
  for f in .github/agents/*.md; do
    [ -f "$f" ] || continue
    base=$(basename "$f" | sed -e 's/\.agent\.md$//' -e 's/\.md$//')
    nm=$(awk '/^---[[:space:]]*$/{c++;next} c==1&&/^name:/{sub(/^name:[[:space:]]*/,"");print;exit}' "$f")
    desc=$(awk '/^---[[:space:]]*$/{c++;next} c==1&&/^description:/{sub(/^description:[[:space:]]*/,"");print;exit}' "$f")
    probe=$(printf '%s %s' "$nm" "$desc" | tr '[:upper:]' '[:lower:]')
    # Name first, description only as a fallback: descriptions are prose and match too much.
    # *-planner style suffixes count too, since a --prefix install is the expected end state here.
    case "$base" in
      *planner) role="plan" ;;
      *implementer) role="implement" ;;
      *reviewer) role="review" ;;
      *)
        case "$probe" in
          *plan*|*design*|*architect*) role="plan" ;;
          *review*|*audit*|*lint*) role="review" ;;
          *implement*|*refactor*) role="implement" ;;
          *) role="unclear — read it" ;;
        esac ;;
    esac
    case "$base" in
      planner|implementer|reviewer) note='**same name as the template**' ;;
      *-planner|*-implementer|*-reviewer) note='same role as the template, renamed' ;;
      *) note='—' ;;
    esac
    printf '| `%s` | %s | %s | %s |\n' "$base" "${nm:-—}" "$role" "$note"
    N=$((N + 1))
  done
  [ "$N" -eq 0 ] && printf '| none | — | — | — |\n'
  printf '\n> Resolution: one owner per role. Delete or retire the loser, or keep both and record in\n'
  printf '> `AGENTS.md` which one owns what. Do not rely on choosing correctly at pick time.\n'
fi

# ---------------------------------------------------------------- 4. forbidden zones
sec "4. Generated output and forbidden zones (inferred from .gitignore and layout)"

if has .gitignore; then
  printf '`.gitignore` entries related to build output:\n\n```\n'
  grep -vE '^\s*(#|$)' .gitignore | grep -iE 'dist|build|out|coverage|node_modules|venv|vendor|generated|\.next|target|bin|obj|lock' | head -20
  printf '```\n\n'
fi

printf 'Directories that look generated and already exist:\n\n'
GEN=0
for d in dist build out coverage .next target bin obj generated vendor; do
  if [ -d "$d" ]; then printf -- '- `%s/`\n' "$d"; GEN=1; fi
done
[ "$GEN" -eq 0 ] && echo '- None'

printf '\nLockfiles (should not appear in a diff unless dependencies changed):\n\n'
LOCK=0
for f in pnpm-lock.yaml package-lock.json yarn.lock bun.lockb poetry.lock uv.lock Cargo.lock go.sum Gemfile.lock composer.lock; do
  if has "$f"; then printf -- '- `%s`\n' "$f"; LOCK=1; fi
done
[ "$LOCK" -eq 0 ] && echo '- None'

# ---------------------------------------------------------------- 5. directory map
sec "5. Directory map (top level only; use it to fill in the placement table)"

printf '| Directory | Files | Main types |\n| --- | --- | --- |\n'
D=0
for d in */; do
  case "$d" in
    node_modules/|.git/|.venv/|venv/|dist/|build/|target/|vendor/|.idea/|.next/) continue ;;
  esac
  n=$(find "$d" \( $PRUNE \) -prune -o -type f -print 2>/dev/null | wc -l | tr -d ' ')
  [ "$n" -eq 0 ] && continue
  exts=$(find "$d" \( $PRUNE \) -prune -o -type f -print 2>/dev/null \
    | awk -F/ '{n=$NF; if (n ~ /\./) {sub(/.*\./,"",n); print n}}' \
    | sort | uniq -c | sort -rn | head -3 | awk '{printf "%s(%s) ", $2, $1}')
  printf '| `%s` | %s | %s |\n' "$d" "$n" "$(echo "$exts" | sed 's/ *$//')"
  D=$((D + 1))
  [ "$D" -ge 20 ] && break
done
# `*/` does not match hidden dirs, but .github holds instructions and agent definitions.
if [ -d .github ]; then
  n=$(find .github \( $PRUNE \) -prune -o -type f -print 2>/dev/null | wc -l | tr -d ' ')
  exts=$(find .github \( $PRUNE \) -prune -o -type f -print 2>/dev/null \
    | awk -F/ '{n=$NF; if (n ~ /\./) {sub(/.*\./,"",n); print n}}' \
    | sort | uniq -c | sort -rn | head -3 | awk '{printf "%s(%s) ", $2, $1}')
  printf '| `.github/` | %s | %s |\n' "$n" "$(echo "$exts" | sed 's/ *$//')"
  D=$((D + 1))
fi
[ "$D" -eq 0 ] && printf '| No subdirectories | 0 | — |\n'

# ---------------------------------------------------------------- 6. human only
cat <<'EOF'

## 6. What only a human can fill in

Do **not** let a tool or an agent guess these three. They are invisible in the code, and a wrong
guess will mislead every agent for months.

### 6.1 Architecture invariants

One sentence on who may call whom, in a form a **linter could enforce**:

- Dependency direction: `api -> service -> repository`, never backwards (by default `repository`
  may not reference `service`)
- Cross-module rule: modules talk only through the interface exposed by `index.ts`
- State ownership: only `store/` may hold mutable global state

### 6.2 Prohibition boundaries (beyond auto-detection)

- Directories that require asking a human before changing:
- Files that are externally generated and must never be hand-edited:
- When lockfiles may be modified:

### 6.3 Process prohibitions

- Never modify tests, delete assertions, or add ignore comments to get CI green
- Never add dependencies on your own
- Never modify `.github/workflows/`
- Other:

---

**Next step**: paste sections 1-5 into the matching parts of `AGENTS.md`, **execute** every command
from section 2 to confirm it works, and write section 6 by hand.
EOF
